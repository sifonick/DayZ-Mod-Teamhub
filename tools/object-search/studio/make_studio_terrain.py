"""Generate the Patch Atlas Studio terrain: a flat, plain, empty DayZ world.

Writes an Addon Builder source folder (default: ./pa_studio) containing
    config.cpp                  world definition (CfgWorlds class "pa_studio")
    world/pa_studio.wrp         terrain in the editable 8WVR format Terrain Builder exports
    data/pa_studio_floor.rvmat  the one terrain material (plain colours, no image files)

Addon Builder's "Binarize" converts the .wrp into the game's format when you pack it.

The 8WVR layout matches Bohemia's DayZ terrain sample (Test_Terrain/world/utes.wrp):
    "8WVR", uint texGridX, texGridY, heightGridX, heightGridY, float texCellSize,
    float heights[hY][hX], uint16 texIndex[tY][tX],
    uint nTextures, then for each texture after the empty slot 0: uint 0, uint len, chars,
    then uint 0, then object records (none here).

Usage:  python make_studio_terrain.py [output_folder] [--height 20] [--floor 0.55]
"""
import argparse
import os
import struct

PREFIX = "pa_studio"
TEX_GRID = 128       # terrain material grid (cells)
TEX_CELL = 40.0      # metres per material cell  -> 128 * 40 = 5120 m world
HEIGHT_GRID = 512    # height samples per side   -> 10 m between samples
WORLD_SIZE = TEX_GRID * TEX_CELL


def write_wrp(path, height, material):
    with open(path, "wb") as f:
        f.write(b"8WVR")
        f.write(struct.pack("<4I", TEX_GRID, TEX_GRID, HEIGHT_GRID, HEIGHT_GRID))
        f.write(struct.pack("<f", TEX_CELL))
        f.write(struct.pack("<f", height) * (HEIGHT_GRID * HEIGHT_GRID))
        f.write(struct.pack("<H", 1) * (TEX_GRID * TEX_GRID))      # every cell uses texture 1
        name = material.encode("ascii")
        f.write(struct.pack("<I", 2))                                # slot 0 (empty) + our material
        f.write(struct.pack("<2I", 0, len(name)) + name)
        f.write(struct.pack("<I", 0))
        # no objects: the object list runs to the end of the file


def read_wrp(path):
    """Parse an 8WVR file the same way (used to check the output, and against Bohemia's sample)."""
    d = open(path, "rb").read()
    assert d[:4] == b"8WVR", "not an 8WVR file"
    tx, ty, hx, hy = struct.unpack_from("<4I", d, 4)
    o = 24 + hx * hy * 4 + tx * ty * 2
    n = struct.unpack_from("<I", d, o)[0]; o += 4
    names = []
    for _ in range(n - 1):
        zero, ln = struct.unpack_from("<2I", d, o); o += 8
        assert zero == 0
        names.append(d[o:o + ln].decode("ascii")); o += ln
    assert struct.unpack_from("<I", d, o)[0] == 0; o += 4
    objects = 0
    while o < len(d):
        o += 48
        _oid, ln = struct.unpack_from("<2I", d, o); o += 8 + ln
        objects += 1
    assert o == len(d), "trailing bytes"
    heights = struct.unpack_from(f"<{hx * hy}f", d, 24)
    return {"grid": (tx, ty, hx, hy), "textures": names, "objects": objects,
            "height": (min(heights), max(heights))}


def floor_rvmat(floor):
    g = f"{floor:.3f}"
    # Same stages as a Terrain Builder tile material, with plain generated colours:
    # Stage0 satellite colour, Stage1 surface mask (black = first surface everywhere),
    # Stage2 detail tint, Stage3/4 the surface's normal map and colour, Stage14 terrain normal.
    uv = """	class uvTransform
	{
		aside[]={0.001953125,0,0};
		up[]={0,0,0.001953125};
		dir[]={0,-0.001953125,0};
		pos[]={0.03125,10.03125,0};
	};"""
    tex = lambda scale: f"""	class uvTransform
	{{
		aside[]={{{scale},0,0}};
		up[]={{0,{scale},0}};
		dir[]={{0,0,{scale}}};
		pos[]={{0,0,0}};
	}};"""
    return f"""ambient[]={{0.9,0.9,0.9,1}};
diffuse[]={{0.9,0.9,0.9,1}};
forcedDiffuse[]={{0.02,0.02,0.02,1}};
emmisive[]={{0,0,0,0}};
specular[]={{0,0,0,0}};
specularPower=0;
class Stage0
{{
	texture="#(rgb,8,8,3)color({g},{g},{g},1,co)";
	texGen=3;
}};
class Stage1
{{
	texture="#(argb,8,8,3)color(0,0,0,1,ca)";
	texGen=4;
}};
class TexGen3
{{
	uvSource="worldPos";
{uv}
}};
class TexGen4
{{
	uvSource="worldPos";
{uv}
}};
class TexGen0
{{
	uvSource="tex";
{tex(1)}
}};
class TexGen1
{{
	uvSource="tex";
{tex(10)}
}};
class TexGen2
{{
	uvSource="tex";
{tex(10)}
}};
PixelShaderID="TerrainSNX";
VertexShaderID="Terrain";
class Stage2
{{
	texture="#(rgb,1,1,1)color(0.5,0.5,0.5,1,cdt)";
	texGen=0;
}};
class Stage3
{{
	texture="#(argb,8,8,3)color(0.5,0.5,1,1,nopx)";
	texGen=1;
}};
class Stage4
{{
	texture="#(argb,8,8,3)color(0.5,0.5,0.5,1,ca)";
	texGen=2;
}};
class Stage14
{{
	texture="#(rgb,8,8,3)color(0.5,0.5,1,1,nohq)";
	texGen=3;
}};
"""


