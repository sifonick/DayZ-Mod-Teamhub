def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", nargs="?", default=PREFIX)
    ap.add_argument("--height", type=float, default=20.0, help="floor height above sea level, metres")
    ap.add_argument("--floor", type=float, default=0.55, help="floor brightness 0-1 (0.55 = mid grey)")
    args = ap.parse_args()
    os.makedirs(os.path.join(args.out, "world"), exist_ok=True)
    os.makedirs(os.path.join(args.out, "data"), exist_ok=True)
    material = f"{PREFIX}\\data\\pa_studio_floor.rvmat"
    wrp = os.path.join(args.out, "world", "pa_studio.wrp")
    write_wrp(wrp, args.height, material)
    with open(os.path.join(args.out, "data", "pa_studio_floor.rvmat"), "w", newline="\r\n") as f:
        f.write(floor_rvmat(args.floor))
    with open(os.path.join(args.out, "config.cpp"), "w", newline="\r\n") as f:
        f.write(world_config(args.height, args.floor))
    info = read_wrp(wrp)
    print(f"Wrote {args.out}: {WORLD_SIZE:.0f} m square, flat at {args.height} m, "
          f"material {info['textures']}, {info['objects']} objects")


if __name__ == "__main__":
    main()
